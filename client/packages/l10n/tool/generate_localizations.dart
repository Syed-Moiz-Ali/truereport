import 'dart:convert';
import 'dart:io';

/// Generates the `AppLocalizations` accessors from the backend catalogs.
///
/// Run: `dart run tool/generate_localizations.dart`
///
/// Sources (backend is the single source of truth; no English is shipped here):
///   server/src/main/resources/i18n/schema.json          key + placeholder shape
///   server/src/main/resources/i18n/workshop_admin/en.json  message bodies (shape only)
///
/// Output:
///   lib/l10n/gen/app_localizations.dart
///   lib/l10n/gen/app_localizations_en.dart
///
/// Every getter is `remoteEnglish('<key>')`; every parameterized method is
/// `remoteFormat('<key>', {...})`. No literal English fallback is emitted.
const String _abstractPath = 'lib/l10n/gen/app_localizations.dart';
const String _englishPath = 'lib/l10n/gen/app_localizations_en.dart';

/// Builds both generated files without writing them.
///
/// Exposed so the idempotence test can compare a fresh run with the files on
/// disk.
Map<String, String> buildLocalizationFiles() {
  final root = repoRoot();
  final schema = _readObject(
    '${root.path}${Platform.pathSeparator}server${Platform.pathSeparator}src'
    '${Platform.pathSeparator}main${Platform.pathSeparator}resources'
    '${Platform.pathSeparator}i18n${Platform.pathSeparator}schema.json',
  );
  final values = <String, String>{};
  for (final scope in const <String>['workshop_admin', 'technician']) {
    final catalog = _readObject(
      '${root.path}${Platform.pathSeparator}server${Platform.pathSeparator}src'
      '${Platform.pathSeparator}main${Platform.pathSeparator}resources'
      '${Platform.pathSeparator}i18n${Platform.pathSeparator}$scope'
      '${Platform.pathSeparator}en.json',
    );
    for (final entry in catalog.entries) {
      final value = entry.value;
      if (value is String) values.putIfAbsent(entry.key, () => value);
    }
  }
  final keys = schema['keys'];
  if (keys is! Map) {
    throw StateError('schema.json is missing "keys"');
  }

  final declarations = StringBuffer();
  final implementations = StringBuffer();

  for (final entry in keys.entries) {
    final key = entry.key as String;
    final meta = entry.value is Map
        ? entry.value as Map
        : const <String, dynamic>{};
    final placeholders = _placeholders(meta['placeholders']);
    final value = values[key];
    final text = value is String ? value : '';
    final ordered = _orderedParams(text, placeholders);

    if (ordered.isEmpty) {
      declarations.writeln('  String get $key;');
      implementations
        ..writeln('  @override')
        ..writeln("  String get $key => remoteEnglish('$key');")
        ..writeln();
      continue;
    }

    final signature = ordered
        .map((param) => '${param.type} ${param.name}')
        .join(', ');
    declarations.writeln('  String $key($signature);');
    final args = ordered
        .map((param) => "'${param.name}': ${param.name}")
        .join(', ');
    implementations
      ..writeln('  @override')
      ..writeln("  String $key($signature) =>")
      ..writeln("      remoteFormat('$key', {$args});")
      ..writeln();
  }

  final abstractContent =
      '''
// GENERATED by tool/generate_localizations.dart - do not edit by hand.
// Source: server/src/main/resources/i18n/schema.json
import 'dart:async';

import 'package:flutter/foundation.dart';
import 'package:flutter/widgets.dart';
import 'package:flutter_localizations/flutter_localizations.dart';
import 'package:intl/intl.dart' as intl;

import 'app_localizations_en.dart';

// ignore_for_file: type=lint

/// Every string is served by the backend UI-message bundle.
abstract class AppLocalizations {
  AppLocalizations(String locale)
    : localeName = intl.Intl.canonicalizedLocale(locale.toString());

  final String localeName;

  static AppLocalizations of(BuildContext context) {
    return Localizations.of<AppLocalizations>(context, AppLocalizations)!;
  }

  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();

  static const List<LocalizationsDelegate<dynamic>> localizationsDelegates =
      <LocalizationsDelegate<dynamic>>[
        delegate,
        GlobalMaterialLocalizations.delegate,
        GlobalCupertinoLocalizations.delegate,
        GlobalWidgetsLocalizations.delegate,
      ];

  static const List<Locale> supportedLocales = <Locale>[Locale('en')];

$declarations}

class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  Future<AppLocalizations> load(Locale locale) {
    return SynchronousFuture<AppLocalizations>(lookupAppLocalizations(locale));
  }

  @override
  bool isSupported(Locale locale) =>
      <String>['en'].contains(locale.languageCode);

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}

AppLocalizations lookupAppLocalizations(Locale locale) {
  switch (locale.languageCode) {
    case 'en':
      return AppLocalizationsEn();
  }

  throw FlutterError('unsupportedLocale');
}
''';

  final englishContent =
      '''
// GENERATED by tool/generate_localizations.dart - do not edit by hand.
// Source: server/src/main/resources/i18n/*/en.json
// ignore: unused_import
import 'package:intl/intl.dart' as intl;

import 'app_localizations.dart';
import '../../src/remote_english.dart';

// ignore_for_file: type=lint

class AppLocalizationsEn extends AppLocalizations {
  AppLocalizationsEn([String locale = 'en']) : super(locale);

$implementations}
''';

  return <String, String>{
    _abstractPath: abstractContent,
    _englishPath: englishContent,
  };
}

void main() {
  final files = buildLocalizationFiles();
  for (final entry in files.entries) {
    final file = File(entry.key);
    file.parent.createSync(recursive: true);
    file.writeAsStringSync(entry.value);
    stdout.writeln('wrote ${entry.key}');
  }
}

Directory repoRoot() {
  var directory = Directory.current;
  for (var i = 0; i < 8; i++) {
    final marker = File(
      '${directory.path}${Platform.pathSeparator}server${Platform.pathSeparator}src'
      '${Platform.pathSeparator}main${Platform.pathSeparator}resources'
      '${Platform.pathSeparator}i18n${Platform.pathSeparator}schema.json',
    );
    if (marker.existsSync()) return directory;
    if (directory.parent.path == directory.path) break;
    directory = directory.parent;
  }
  throw StateError(
    'Could not locate server/src/main/resources/i18n/schema.json from '
    '${Directory.current.path}',
  );
}

Map<String, dynamic> _readObject(String path) {
  final file = File(path);
  if (!file.existsSync()) {
    throw StateError('Missing catalog: $path');
  }
  final decoded = jsonDecode(file.readAsStringSync());
  if (decoded is! Map) throw StateError('Not a JSON object: $path');
  return Map<String, dynamic>.from(decoded);
}

class _Placeholder {
  const _Placeholder(this.name, this.type);
  final String name;
  final String type;
}

List<_Placeholder> _placeholders(Object? raw) {
  if (raw is! Map) return const <_Placeholder>[];
  final result = <_Placeholder>[];
  for (final entry in raw.entries) {
    final name = entry.key as String;
    final meta = entry.value is Map
        ? entry.value as Map
        : const <String, dynamic>{};
    result.add(_Placeholder(name, _dartType(meta['type'])));
  }
  return result;
}

String _dartType(Object? raw) {
  switch (raw is String ? raw : '') {
    case 'int':
      return 'int';
    case 'double':
      return 'double';
    case 'num':
      return 'num';
    case 'DateTime':
      return 'DateTime';
    case 'String':
      return 'String';
    default:
      return 'Object';
  }
}

/// Orders placeholders by first top-level appearance in the message body.
///
/// Nested ICU clauses (`{count, plural, =1{...}}`) are skipped so words inside
/// them are never mistaken for parameters.
List<_Placeholder> _orderedParams(
  String message,
  List<_Placeholder> placeholders,
) {
  final positions = <String, int>{};
  var index = 0;
  while (index < message.length) {
    final open = message.indexOf('{', index);
    if (open < 0) break;
    final close = _matchingBrace(message, open);
    if (close < 0) break;
    final body = message.substring(open + 1, close);
    final name = RegExp(r'^\s*([A-Za-z_][A-Za-z0-9_]*)')
        .firstMatch(body)
        ?.group(1);
    if (name != null && !positions.containsKey(name)) {
      final declared = placeholders.any((item) => item.name == name);
      if (declared) positions[name] = open;
    }
    index = close + 1;
  }

  final ordered = <_Placeholder>[];
  final names = positions.keys.toList()
    ..sort((a, b) => positions[a]!.compareTo(positions[b]!));
  for (final name in names) {
    ordered.add(placeholders.firstWhere((item) => item.name == name));
  }
  // Any declared-but-unused placeholder keeps a stable position at the end.
  for (final placeholder in placeholders) {
    if (!ordered.any((item) => item.name == placeholder.name)) {
      ordered.add(placeholder);
    }
  }
  return ordered;
}

int _matchingBrace(String text, int open) {
  var depth = 0;
  for (var i = open; i < text.length; i++) {
    if (text[i] == '{') depth += 1;
    if (text[i] == '}') {
      depth -= 1;
      if (depth == 0) return i;
    }
  }
  return -1;
}
